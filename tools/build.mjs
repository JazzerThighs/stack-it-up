import {versionBuild} from './version-build.mjs';
import {spawnSync} from 'node:child_process';
import {mkdir,copyFile,cp,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
const settings=spawnSync(process.execPath,['tools/generate-settings.mjs','--check'],{cwd:root,stdio:'inherit'});
if(settings.status!==0)process.exit(settings.status||1);
const contract=spawnSync(process.execPath,['tools/generate-game-contract.mjs','--check'],{cwd:root,stdio:'inherit'});
if(contract.status!==0)process.exit(contract.status||1);
const abi=spawnSync(process.execPath,['tools/generate-abi.mjs','--check'],{cwd:root,stdio:'inherit'});
if(abi.status!==0)process.exit(abi.status||1);
const types=spawnSync(process.execPath,['tools/typecheck.mjs'],{cwd:root,stdio:'inherit'});
if(types.status!==0)process.exit(types.status||1);
const catalog=spawnSync(process.execPath,['tools/generate-pieces.mjs','--check'],{cwd:root,stdio:'inherit'});
if(catalog.status!==0)process.exit(catalog.status||1);
const result=spawnSync('cargo',['build','--offline','--release','--target','wasm32-unknown-unknown'],{cwd:root,stdio:'inherit'});
if(result.status!==0)process.exit(result.status||1);
const output=path.resolve(root,'dist');
if(path.dirname(output)!==path.resolve(root)||path.basename(output)!=='dist')throw Error('Invalid build output');
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
await cp(path.join(root,'web'),path.join(root,'dist'),{recursive:true});
await copyFile(path.join(root,'target/wasm32-unknown-unknown/release/cube_stack.wasm'),path.join(root,'dist/cube_stack.wasm'));
const data=spawnSync(process.execPath,['tools/build-packing-data.mjs',path.join(output,'explorer/data')],{cwd:root,stdio:'inherit'});
if(data.status!==0)process.exit(data.status||1);
const version=await versionBuild(output);
console.log(`Built dist/ (${version}). Run: node tools/serve.mjs`);
