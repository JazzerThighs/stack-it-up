import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const rootArg=process.argv.indexOf('--root');
const root=rootArg<0?new URL('../',import.meta.url):pathToFileURL(path.resolve(process.argv[rootArg+1])+path.sep),check=process.argv.includes('--check');
const outputs=new Map();
for(const name of ['appearance','display','controls','orbit']){
const schema=JSON.parse(readFileSync(new URL('data/'+name+'-settings.json',root),'utf8'));
for(const spec of Object.values(schema.fields))if(spec.optionSet){
 const options=schema.optionSets?.[spec.optionSet];if(!options)throw Error('Unknown option set '+spec.optionSet);
 const entries=[...options,...(spec.extraOptions||[])];
 spec.options=entries.map(([value])=>value);spec.optionLabels=entries.map(([,label])=>label);
}
if(schema.version!==1||!schema.storageKey)throw Error('Invalid settings schema version/key');
const escape=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
for(const [id,s] of Object.entries(schema.fields)){
 if(!/^[a-zA-Z][\w]*$/.test(id)||!s.label||!['input','change'].includes(s.commit))throw Error('Invalid setting '+id);
 if(s.group&&(s.select||s.color))throw Error('Keep custom controls explicit: '+id);
 if(s.group&&!schema.groups.includes(s.group))throw Error('Unknown control group '+id);
 if(s.options){if(!s.options.includes(s.value)||new Set(s.options).size!==s.options.length||s.optionLabels?.length!==s.options.length)throw Error('Invalid options '+id);}
 else if(typeof s.value==='boolean'){if(!s.checkbox)throw Error('Boolean requires checkbox '+id);}
 else if(s.color){if(!/^#[\da-f]{6}$/i.test(s.value))throw Error('Invalid color default '+id);}
 else if(![s.min,s.max,s.step,s.value].every(Number.isFinite)||s.step<=0||s.min>s.max||s.value<s.min||s.value>s.max)throw Error('Invalid numeric bounds/default '+id);
 if(s.wrapper&&!schema.availability[s.wrapper])throw Error('Missing visibility condition '+id);
}
function dependencies(c){
 if(c.any||c.all){const list=c.any||c.all;if(!Array.isArray(list)||!list.length)throw Error('Empty condition');return list.flatMap(dependencies);}
 if(!/^[a-zA-Z][\w]*$/.test(c.id)||!(Array.isArray(c.values)&&c.values.length||typeof c.checked==='boolean'))throw Error('Invalid condition');
 return [c.id];
}
const dependencyIds=Object.values(schema.availability).flatMap(dependencies);
outputs.set('web/ui/'+name+'-schema.js','// Generated by tools/generate-settings.mjs; edit data/'+name+'-settings.json.\nexport const '+name+'Schema = '+JSON.stringify(schema,null,2)+';\n');
function control(id,s){
 if(s.nested)return '<label class="camera-range" for="'+id+'"><span>'+escape(s.label)+' <output id="'+id+'Value" for="'+id+'">'+s.value+'</output> '+escape(s.unit||'')+'</span><input id="'+id+'" type="range" min="'+s.min+'" max="'+s.max+'" step="'+s.step+'" value="'+s.value+'"></label>';
 if(s.options)return '<div class="setting-row"><label for="'+id+'">'+escape(s.label)+'<select id="'+id+'">'+s.options.map((v,i)=>'<option value="'+escape(v)+'"'+(v===s.value?' selected':'')+'>'+escape(s.optionLabels[i])+'</option>').join('')+'</select></label></div>';
 const out=`<output id="${id}Value" for="${id}">${s.checkbox?(s.value?'On':'Off'):escape(s.value+(s.unit||''))}</output>`;
 const attrs=s.checkbox?`type="checkbox"${s.value?' checked':''}`:`type="range" min="${s.min}" max="${s.max}" step="${s.step}" value="${s.value}"`;
 const input=`<input id="${id}" ${attrs}${s.help?` aria-describedby="${id}Help"`:''}>`;
 const body=`<label for="${id}">${s.checkbox?input+' ':''}${escape(s.label)} ${out}</label>${s.checkbox?'':input}${s.help?`<p class="muted" id="${id}Help">${escape(s.help)}</p>`:''}`;
 return `<div${s.wrapper?` id="${s.wrapper}"`:''} class="setting-row">${body}</div>`;
}
for(const file of ['web/index.html','web/explorer/index.html']){
 let html=outputs.get(file)||readFileSync(new URL(file,root),'utf8');
 for(const group of schema.groups){
  const re=new RegExp(`<!-- settings:${group}:start -->[\\s\\S]*?<!-- settings:${group}:end -->`,'g');
  if([...html.matchAll(re)].length!==1)throw Error('Missing/duplicate slot '+file+':'+group);
  const controls=Object.entries(schema.fields).filter(([,s])=>s.group===group).sort((a,b)=>(a[1].order||0)-(b[1].order||0)).map(([id,s])=>control(id,s)).join('\n');
  html=html.replace(re,`<!-- settings:${group}:start -->\n${controls}\n<!-- settings:${group}:end -->`);
 }
 const app=file==='web/index.html'?'game':'explorer';
 const ids=Object.entries(schema.fields).map(([id,s])=>s.controlIds&&Object.hasOwn(s.controlIds,app)?s.controlIds[app]:id).filter(Boolean);
 for(const id of [...ids,...dependencyIds,...Object.keys(schema.availability)])if([...html.matchAll(new RegExp(`\\bid="${id}"`,'g'))].length!==1)throw Error('Missing/duplicate control '+file+':'+id);
 outputs.set(file,html);
}
}
for(const [name,file]of [['game','web/style.css'],['explorer','web/explorer/workspace.css']]){
 const css=readFileSync(new URL('web/ui/'+name+'-settings.css',root),'utf8').trimEnd();
 const original=readFileSync(new URL(file,root),'utf8');
 const start='/* settings-css:'+name+':start */',end='/* settings-css:'+name+':end */';
 const a=original.indexOf(start),b=original.indexOf(end,a);
 if(a<0||b<0||original.indexOf(start,a+1)>=0)throw Error('Missing/duplicate CSS slot '+file);
 outputs.set(file,original.slice(0,a)+start+'\n'+css+'\n'+original.slice(b));
}
let stale=false;for(const [file,content]of outputs){let previous;try{previous=readFileSync(new URL(file,root),'utf8');}catch{}if(previous===content)continue;if(check){console.error('Stale generated settings: '+file);stale=true;}else writeFileSync(new URL(file,root),content);}
if(stale)process.exitCode=1;else console.log('Verified shared settings schemas and generated controls');
