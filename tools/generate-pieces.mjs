const check=process.argv.includes('--check');
const xyz=i=>[Math.floor(i/9),Math.floor(i/3)%3,i%3];
const kind=i=>xyz(i).filter(v=>v!==1).length;
const permutations=[[0,1,2],[0,2,1],[1,0,2],[1,2,0],[2,0,1],[2,1,0]];
const rotations=[];
for(const axes of permutations) {
  const odd=axes.reduce((n,a,i)=>n+axes.slice(i+1).filter(b=>a>b).length,0)%2;
  for(const x of [-1,1])for(const y of [-1,1])for(const z of [-1,1])
    if((odd?-1:1)*x*y*z===1)rotations.push({axes,signs:[x,y,z]});
}
function placements(cells) {
  const masks=new Set();
  for(const {axes,signs} of rotations) {
    let points=cells.map(p=>axes.map((a,i)=>p[a]*signs[i]));
    const min=[0,1,2].map(a=>Math.min(...points.map(p=>p[a])));
    points=points.map(p=>p.map((v,a)=>v-min[a]));
    const max=[0,1,2].map(a=>Math.max(...points.map(p=>p[a])));
    for(let x=0;x<3-max[0];x++)for(let y=0;y<3-max[1];y++)for(let z=0;z<3-max[2];z++)
      masks.add(points.reduce((m,p)=>m|(1<<((p[0]+x)*9+(p[1]+y)*3+p[2]+z)),0));
  }
  return [...masks].sort((a,b)=>a-b);
}
if(source.version!==1||source.pieces.map(p=>p.letter).join('')!=='OTLJSZBDF')throw Error('Invalid piece schema/order');
const pieces=source.pieces.map((p,i)=>{
  if(p.id!==i+1||!/^#[0-9a-f]{6}$/.test(p.color)||p.cells.length!==4||
    p.cells.some(c=>c.length!==3||c.some(v=>!Number.isInteger(v)||v<0||v>2))||
    new Set(p.cells.map(c=>c.join(','))).size!==4)throw Error(`Invalid piece ${p.letter}`);
  const seen=new Set([0]);
  for(let pass=0;pass<4;pass++)for(let a=0;a<4;a++)for(let b=0;b<4;b++)
    if(seen.has(a)&&p.cells[a].reduce((d,v,k)=>d+Math.abs(v-p.cells[b][k]),0)===1)seen.add(b);
  if(seen.size!==4)throw Error(`Disconnected piece ${p.letter}`);
  if(!p.spatial && JSON.stringify(p.cells)!==JSON.stringify(p.planar.map(c=>[...c,0])))throw Error('Planar seed mismatch');
  const all=placements(p.cells),surface=all.filter(m=>!(m&(1<<13)));
  const compositions=[...new Set(surface.map(mask=>{
    const counts=[0,0,0];for(let j=0;j<27;j++)if(mask&(1<<j))counts[kind(j)-1]++;
    return counts.join(',');
  }))].sort().map(s=>s.split(',').map(Number));
  const inventory=[0,1,2].map(a=>Math.max(...compositions.map(c=>c[a])));
  return {...p,placements:all,surfacePlacements:surface,surfaceCompositions:compositions,surfaceInventory:inventory};
});
