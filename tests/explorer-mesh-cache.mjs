import assert from 'node:assert/strict';
import {explorationMeshes} from '../web/explorer/exploration-mesh.js';
import {cellFragments,joinMeshes} from '../web/render/cell-fragments.js';
import {visualSettings} from '../web/render/visual-settings.js';
const cells=Array.from({length:27},(_,i)=>[0,3,6,7].includes(i)?{piece:0,color:'o'}:null);
const generate=()=>{throw Error('Angular geometry needs no Wasm');};
const build=state=>explorationMeshes(state,generate,'angular',false,false,true,false,{},false,'whole')[0];
const first=build(cells),copy=joinMeshes([first]),fragments=cellFragments(first);
assert.deepEqual(first,copy,'Preserving identity does not change geometry or coverage');
const repeat=build(cells.map(c=>c&&({...c})));
assert.equal(repeat,first,'Equivalent states reuse the cached piece, not a fresh joined array');
assert.equal(cellFragments(repeat),fragments,'Closed fragment preparation stays cached');
const changed=build(cells.map(c=>c&&({...c,color:'b'})));
assert.notEqual(changed,first,'Recoloring is not a stale hit');
const previous=visualSettings.cubieScale;visualSettings.cubieScale=80;
assert.notEqual(build(cells),first,'Size changes are not stale hits');visualSettings.cubieScale=previous;
assert.equal(build(cells),first);
assert.deepEqual(first,copy,'Fragment preparation leaves the shared source immutable');
console.log('PASS: explorer reuses immutable whole-piece arrays and closed fragments; colors and sizing still invalidate geometry.');
