import assert from 'node:assert/strict';
import fs from 'node:fs';
import {adaptEngine} from '../web/engine/wasm.js';
import {S} from '../web/engine/snapshot.js';
import {activeCubie,rebuildSlots} from '../web/render/active-cubie.js';
import {visualSettings} from '../web/render/visual-settings.js';
import {landedState} from '../web/ui/animations.js';
import {turn} from '../web/explorer/model.js';
const {instance}=await WebAssembly.instantiate(fs.readFileSync(new URL('../dist/cube_stack.wasm',import.meta.url)));
const engine=adaptEngine(instance.exports);engine.game_init(1);
const header=engine.exportState().slice(0,22);
header[3]=1<<26;header[4]=16;header[11]=1;header[15]=1;header[18]=0;header[19]=0;
const cells=[0,1,3,4,18,19,21,22];
const floating=cells.flatMap((cell,i)=>[cell,2,i<4?10:16]);
const fixture=[...header,...Array(54).fill(0),2,1,2,8,...floating,2,10,16,0,0,0,1];
assert(engine.importState(fixture));
const state=engine.snapshot(),view={rebuildSolidIdentities:true,rebuildSlots:rebuildSlots(state)};
assert.equal(state.rebuildIds[0],10);assert.equal(state.rebuildIds[18],16);
assert.equal(view.rebuildSlots.get(10),0);assert.equal(view.rebuildSlots.get(16),1);
const geometry=cell=>{const mesh=[];activeCubie(mesh,[0,0,0],.438,[1,0,0],cell,state,view);return mesh;};
visualSettings.solidGray=1;
const tetra=geometry(0),cube=geometry(18);
assert.equal(tetra.length/27,4);assert.equal(cube.length/27,12);
assert.notEqual(tetra[6],cube[6]);
for(const mesh of [tetra,cube])for(let i=0;i<mesh.length;i+=9)assert(mesh[i+6]===mesh[i+7] && mesh[i+7]===mesh[i+8]);
visualSettings.solidGray=0;assert.deepEqual(geometry(0).slice(6,9),[1,0,0]);
visualSettings.solidGray=1;
for(let move=0;move<30;move++) {
  const preview=landedState(state,move);
  assert.deepEqual(Array.from(preview.rebuildIds),turn(Array.from(state.rebuildIds),move));
}
assert.equal(engine.game_turn(0),1);
assert.deepEqual(Array.from(engine.snapshot().rebuildIds),turn(Array.from(state.rebuildIds),0));
assert.equal(engine.game_undo(),1);
assert.deepEqual(Array.from(engine.snapshot().rebuildIds),Array.from(state.rebuildIds));
assert.deepEqual(engine.exportState(),fixture,'rendering has not changed reconstruction rules or transport');
const html=fs.readFileSync(new URL('../web/index.html',import.meta.url),'utf8');
const menu=html.slice(html.indexOf('<summary>Transparency</summary>')).split('</details>')[0];
for(const id of ['ditherTransparency','activeTransparency','centerTransparency','stackTransparency'])assert(menu.includes(`id="${id}"`));
console.log('PASS: same-color freed IDs retain distinct solid/gray identities through turns and undo; all game opacity controls share one menu.');
