import './fixtures/behavior-defaults.mjs';
import assert from 'node:assert/strict';
import {controlsSchema} from '../web/ui/controls-schema.js';
import {createSettingsStore} from '../web/ui/settings-store.js';
const saved=new Map();globalThis.localStorage={getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)};
const {controlSettings,bindControlSettings,setControlSetting,resetControlSettings}=await import('../web/input/control-settings.js');
const root=explorer=>{
 const elements=Object.fromEntries(Object.keys(controlSettings).map(k=>[explorer&&k==='perspectiveCamera'?'explorerCamera':k,{checked:false,value:'',addEventListener(t,f){this.change=f;}}]));
 return {elements,getElementById:k=>elements[k]};
};
const game=root(false),explorer=root(true);let updates=0;
// Explorer has no game-only timing controls or reset buttons. Its real smoke
// fixture throws on missing lookups, before optional chaining can help.
const gameOnly=new Set(['turnAnimationReset','bluetoothSliceReset','bluetoothWideReset',
 ...Object.entries(controlsSchema.fields).filter(([,s])=>s.controlIds?.explorer===null).flatMap(([k])=>[k,k+'Value'])]);
for(const id of gameOnly)delete explorer.elements[id];
explorer.getElementById=id=>{assert(!gameOnly.has(id),`Explorer must not look up game-only ${id}`);return explorer.elements[id];};
game.elements.turnAnimationReset={addEventListener(type,handler){assert.equal(type,'click');this.click=handler;}};
game.elements.bluetoothSliceWindowValue={textContent:''};
game.elements.bluetoothWideWindowValue={textContent:''};
game.elements.bluetoothNeutralToleranceValue={textContent:''};
const offGame=bindControlSettings(game,()=>updates++),offExplorer=bindControlSettings(explorer,()=>updates++,{explorer:true});
assert(game.elements.hoverRings.checked);assert(explorer.elements.hoverRings.checked);
explorer.elements.hoverRings.checked=false;explorer.elements.hoverRings.change();
assert(!game.elements.hoverRings.checked);assert(game.elements.ringLabels.disabled);
game.elements.showArrows.checked=true;game.elements.showArrows.change();
assert(explorer.elements.showArrows.checked);assert(!explorer.elements.arrowGuides.disabled);
explorer.elements.explorerCamera.value='orthographic';explorer.elements.explorerCamera.change();assert(!game.elements.perspectiveCamera.checked);
game.elements.wideTurns.checked=true;game.elements.wideTurns.change();assert(explorer.elements.wideTurns.checked);
assert(JSON.parse(saved.get('stack-it-up.controls')).values.wideTurns);
game.elements.turnAnimationSpeed.value='2.5';game.elements.turnAnimationSpeed.change();
assert.equal(controlSettings.turnAnimationSpeed,2.5);
assert.equal(JSON.parse(saved.get('stack-it-up.controls')).values.turnAnimationSpeed,2.5);
setControlSetting('turnAnimationSpeed',.25);assert.equal(Number(game.elements.turnAnimationSpeed.value),.25);
assert.equal(setControlSetting('turnAnimationSpeed',NaN),false);
assert.equal(createSettingsStore(controlsSchema,globalThis.localStorage).values.turnAnimationSpeed,.25);
game.elements.turnAnimationReset.click();
assert.equal(controlSettings.turnAnimationSpeed,createSettingsStore(controlsSchema).values.turnAnimationSpeed);
game.elements.bluetoothSliceWindow.value='65';game.elements.bluetoothSliceWindow.change();
assert.equal(controlSettings.bluetoothSliceWindow,65);
assert.equal(createSettingsStore(controlsSchema,globalThis.localStorage).values.bluetoothSliceWindow,65);
setControlSetting('bluetoothSliceWindow',0);assert.equal(controlSettings.bluetoothSliceWindow,0);
assert.equal(setControlSetting('bluetoothSliceWindow',NaN),false);
resetControlSettings('bluetoothSliceWindow');
assert.equal(controlSettings.bluetoothSliceWindow,createSettingsStore(controlsSchema).values.bluetoothSliceWindow);
game.elements.bluetoothWideWindow.value='230';game.elements.bluetoothWideWindow.change();
assert.equal(controlSettings.bluetoothWideWindow,230);
assert.equal(game.elements.bluetoothWideWindowValue.textContent,'230 ms');
assert.equal(createSettingsStore(controlsSchema,globalThis.localStorage).values.bluetoothWideWindow,230);
setControlSetting('bluetoothWideWindow',0);assert.equal(controlSettings.bluetoothWideWindow,0);
assert.equal(setControlSetting('bluetoothWideWindow',NaN),false);
resetControlSettings('bluetoothWideWindow');
assert.equal(controlSettings.bluetoothWideWindow,createSettingsStore(controlsSchema).values.bluetoothWideWindow);
game.elements.bluetoothNeutralTolerance.value='15';game.elements.bluetoothNeutralTolerance.change();
assert.equal(controlSettings.bluetoothNeutralTolerance,15);
assert.equal(game.elements.bluetoothNeutralToleranceValue.textContent,'15 degrees');
assert.equal(createSettingsStore(controlsSchema,globalThis.localStorage).values.bluetoothNeutralTolerance,15);
assert.equal(setControlSetting('bluetoothNeutralTolerance',NaN),false);
resetControlSettings('bluetoothNeutralTolerance');
assert.equal(controlSettings.bluetoothNeutralTolerance,createSettingsStore(controlsSchema).values.bluetoothNeutralTolerance);
for(const [key,value,unit] of [['bluetoothNeutralDelay',375,' ms'],['bluetoothWideSensitivity',5,''],['bluetoothNeutralSpeed',20,'x'],['bluetoothGyroTightness',6,'x'],['bluetoothNeutralCutoff',18,' degrees/s'],['bluetoothGyroResponse',10,' ms'],['bluetoothGyroResponse',500,' ms'],['bluetoothGyroSpeed',240,' degrees/s'],['bluetoothGyroAcceleration',1500,' degrees/s²']]){
 game.elements[key+'Value']={textContent:''};
 game.elements[key].value=String(value);game.elements[key].change();
 assert.equal(controlSettings[key],value);
 assert.equal(game.elements[key+'Value'].textContent,String(value)+unit);
 assert.equal(createSettingsStore(controlsSchema,globalThis.localStorage).values[key],value);
 assert.equal(setControlSetting(key,NaN),false);
 resetControlSettings(key);
 assert.equal(controlSettings[key],createSettingsStore(controlsSchema).values[key]);
}
offGame();offExplorer();const before=updates;setControlSetting('wideTurns',false);assert.equal(before,updates);
console.log('PASS: bidirectional control settings, camera mapping, dependencies, persistence and unsubscribe.');
