import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createLocalGame} from '../web/ui/local-game.js';
import {adaptEngine} from '../web/engine/wasm.js';
const bytes=fs.readFileSync(new URL('../dist/cube_stack.wasm',import.meta.url));
const make=async()=>adaptEngine((await WebAssembly.instantiate(bytes)).instance.exports);
const engine=await make();engine.game_init(123);engine.game_turn(6);
let text=null,writes=0,started=false;
const storage={getItem:()=>text,setItem:(_,v)=>{text=v;writes++;}};
const local=createLocalGame({engine:()=>engine,started:()=>started,chooseNext:()=>true,storage:()=>storage});
assert.equal(local.save(),false);assert.equal(text,null);
started=true;assert(local.save());assert.equal(writes,1);assert(local.save());assert.equal(writes,1);
const expected=engine.exportState();
const fresh=await make();fresh.game_init(456);
const recovering=createLocalGame({engine:()=>fresh,started:()=>true,chooseNext:()=>true,storage:()=>storage});
assert.deepEqual(recovering.restore(),{restored:true,chooseNext:true});
assert.deepEqual(fresh.exportState(),expected);
text='invalid';const before=fresh.exportState();assert(recovering.restore().error);assert.deepEqual(fresh.exportState(),before);
text=JSON.stringify({version:1,words:[0,1]});assert(recovering.restore().error);assert.deepEqual(fresh.exportState(),before);
const denied=createLocalGame({engine:()=>fresh,started:()=>true,chooseNext:()=>false,storage:()=>{throw Error('denied');}});
assert.equal(denied.save(),false);assert(denied.restore().error);
console.log('PASS: real Wasm game auto-save/restore, unchanged-state write suppression, corrupt saves and unavailable storage.');
